import { readFileSync, readdirSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const read = (path: string) => readFileSync(new URL(`../src-tauri/${path}`, import.meta.url), 'utf8')
const capabilities = readdirSync(new URL('../src-tauri/capabilities/', import.meta.url))
  .filter(name => name.endsWith('.json'))
  .map(name => JSON.parse(read(`capabilities/${name}`)))

describe('native diagnostic command access', () => {
  it.each(['get_public_plugin_diagnostics', 'copy_public_plugin_diagnostics'])('%s is wired through the native ACL for main only', command => {
    // UI mocks cannot detect a missing native command permission.
    expect(read('build.rs')).toContain(`"${command}"`)
    expect(read('src/lib.rs')).toContain(`commands::${command}`)
    const permission = `allow-${command.replaceAll('_', '-')}`
    const grants = capabilities.filter(capability => capability.permissions.includes(permission))
    expect(grants).toHaveLength(1)
    expect(grants[0].identifier).toBe('main-capability')
    expect(grants[0].webviews).toEqual(['main'])
    expect(grants[0].windows).toBeUndefined()
    expect(grants[0].remote).toBeUndefined()
    expect(read(`permissions/autogenerated/${command}.toml`)).toContain(`commands.allow = ["${command}"]`)
  })
})