import { readFileSync, readdirSync } from 'node:fs'
import vm from 'node:vm'
import { expect, it, vi } from 'vitest'
function bridge(enabled = true, reply: () => Promise<any> = async () => ({ name: 'a.json', text: '{}', byteLength: 2 })) {
 const source = readFileSync('src-tauri/src/plugin_window.rs','utf8').match(/PUBLIC_CONTENT_BOOTSTRAP: &str = r#"([\s\S]*?)"#;/)![1]!.replace('__PANEL_JSON__', readFileSync('src-tauri/src/public_plugins/panel_action_json.js','utf8')).replace('__WINDOW_ACTIONS__','false').replaceAll('__FILES_OPEN__',String(enabled))
 const invoke = vi.fn(async (command: string) => command === 'plugin_window_open_text' ? reply() : undefined)
 const window: any = { __TAURI_INTERNALS__: { invoke } }
 vm.runInNewContext(source, {window,document:{documentElement:{style:{setProperty(){}}}},TextEncoder,Object,Reflect,Error,TypeError,Promise,WeakSet,setTimeout})
 const prepare=(n='1')=>window.__UIPILOT_PLUGIN_TIMER_PREPARE__({sessionGeneration:n,documentGeneration:'1'})
 return { api: window.uipilotPluginWindow, window, invoke, prepare, async ready() { prepare();window.uipilotPluginWindow.onUpdate(()=>{});await window.__UIPILOT_PLUGIN_WINDOW_UPDATE__({requestId:'r',theme:'light'}) } }
}
it('file facade is opt-in, frozen, exact no-arg, session captured and blocked during ACK',async()=>{
 expect('files' in bridge(false).api).toBe(false)
 const b=bridge(); b.prepare(); const old=b.api.files
 expect(Object.isFrozen(old)).toBe(true)
 await expect(old.openText(1)).rejects.toHaveProperty('name','TypeError')
 b.api.onUpdate(async()=>{ await expect(old.openText()).rejects.toHaveProperty('name','FileOpenBusyError') })
 await b.window.__UIPILOT_PLUGIN_WINDOW_UPDATE__({requestId:'r',theme:'light'})
 const result=await old.openText(); expect(Object.isFrozen(result)).toBe(true)
 expect(b.invoke).toHaveBeenCalledWith('plugin_window_open_text',{sessionGeneration:'1',documentGeneration:'1'})
 b.prepare('2'); await expect(old.openText()).rejects.toHaveProperty('name','ExpiredWindowSessionError')
 expect(b.api.files).not.toBe(old)
})
it('keeps one pending call and rejects stale completion including cancellation and native errors',async()=>{
 for(const outcome of [null,{name:'a',text:'',byteLength:0},'FileOpenFailedError']) {
 let resolve!: (x:any)=>void; let reject!: (x:any)=>void
 const b=bridge(true,()=>new Promise((yes,no)=>{resolve=yes;reject=no})); await b.ready()
 const pending=b.api.files.openText(); await expect(b.api.files.openText()).rejects.toHaveProperty('name','FileOpenBusyError')
 b.prepare('2'); if(typeof outcome==='string')reject(outcome);else resolve(outcome)
 await expect(pending).rejects.toHaveProperty('name','ExpiredWindowSessionError')
 }
})
it('validates exact reply without JSON restrictions and sanitizes errors',async()=>{
 for(const value of [{name:'a',text:'\ud800',byteLength:3},{name:'a',text:'x',byteLength:0},{name:'a/b',text:'',byteLength:0},{name:'a',text:'\0',byteLength:1},{name:'a',text:'x',byteLength:8193},{name:'a',text:'x',byteLength:1,extra:true}]){
 const b=bridge(true,async()=>value); await b.ready(); await expect(b.api.files.openText()).rejects.toHaveProperty('name','FileOpenFailedError')
 }
 for(const value of [null,{name:'a',text:'',byteLength:0},{name:'a',text:'\ufeff x\n',byteLength:6},{name:'a',text:'constructor',byteLength:11}]){
 const b=bridge(true,async()=>value);await b.ready();expect(await b.api.files.openText()).toEqual(value)
 }
 for(const name of ['FileOpenBusyError','FileOpenPermissionError','FileOpenUnsupportedError','FileOpenTooLargeError','FileOpenEncodingError','FileOpenFailedError']){
 const b=bridge(true,async()=>{throw name});await b.ready();await expect(b.api.files.openText()).rejects.toHaveProperty('name',name)
 }
 const b=bridge(true,async()=>{throw new Error('private path')});await b.ready();await expect(b.api.files.openText()).rejects.toHaveProperty('message','FileOpenFailedError')
})

it('grants private file IPC only to plugin window content',()=>{
 const command='plugin_window_open_text'
 for(const [file,value] of [['src-tauri/build.rs',`"${command}"`],['src-tauri/src/lib.rs',`commands::${command}`],[`src-tauri/permissions/autogenerated/${command}.toml`,`commands.allow = ["${command}"]`]])expect(readFileSync(file,'utf8')).toContain(value)
 const grants=readdirSync('src-tauri/capabilities').filter(f=>f.endsWith('.json')).map(f=>JSON.parse(readFileSync(`src-tauri/capabilities/${f}`,'utf8'))).filter(c=>c.permissions.includes('allow-plugin-window-open-text'))
 expect(grants).toHaveLength(1);expect(grants[0].identifier).toBe('plugin-window-content');expect(grants[0].webviews).toEqual(['plugin-content-*'])
})

it('files wait for initial update and successful ACK before admission',async()=>{
 const b=bridge();b.prepare()
 await expect(b.api.files.openText()).rejects.toHaveProperty('name','FileOpenBusyError')
 b.api.onUpdate(()=>{})
 await b.window.__UIPILOT_PLUGIN_WINDOW_UPDATE__({requestId:'r',theme:'light'})
 expect(await b.api.files.openText()).toEqual({name:'a.json',text:'{}',byteLength:2})
})
